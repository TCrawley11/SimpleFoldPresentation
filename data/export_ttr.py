"""Export SimpleFold-3B prediction of wallaby transthyretin (CAMEO22 target 7RLK chain D)
plus the experimental structure, Kabsch-aligned, to assets/data/ttr.js for the deck."""
import gemmi, numpy as np, json, re
PRED='raw/cameo22_predictions/simplefold_3B/7rlk_D_sampled_0.cif'
GT='raw/gt/7rlk.cif'
pst=gemmi.read_structure(PRED); pst.remove_hydrogens()
gst=gemmi.read_structure(GT); gst.remove_hydrogens(); gst.remove_ligands_and_waters()
pch=pst[0][0]; gch=gst[0]['D']
one=lambda r:(gemmi.find_tabulated_residue(r.name).one_letter_code.upper())
pseq=''.join(one(r) for r in pch); gres=[r for r in gch if gemmi.find_tabulated_residue(r.name) and gemmi.find_tabulated_residue(r.name).is_amino_acid()]
gseq=''.join(one(r) for r in gres)
al=gemmi.align_string_sequences(list(gseq),list(pseq),[])
pairs=[];i=j=0
for n,op in re.findall(r'(\d+)([MID])',al.cigar_str()):
    for _ in range(int(n)):
        if op=='M': pairs.append((i,j)); i+=1; j+=1
        elif op=='I': i+=1
        else: j+=1
P=[];Q=[]
for gi,pj in pairs:
    a=gres[gi].find_atom('CA','*'); b=pch[pj].find_atom('CA','*')
    if a and b and gseq[gi]==pseq[pj]: Q.append(a.pos.tolist()); P.append(b.pos.tolist())
P=np.array(P);Q=np.array(Q)
# align prediction onto GT, then center everything on the prediction centroid
Pc,Qc=P.mean(0),Q.mean(0);H=(P-Pc).T@(Q-Qc);U,S,Vt=np.linalg.svd(H);d=np.sign(np.linalg.det(Vt.T@U.T));R=Vt.T@np.diag([1,1,d])@U.T
allp=np.array([a.pos.tolist() for r in pch for a in r]); cen=((allp-Pc)@R.T+Qc).mean(0)
def tp(x): return (np.asarray(x)-Pc)@R.T+Qc-cen
def tg(x): return np.asarray(x)-cen
rmsd=float(np.sqrt(((tp(P)-tg(Q))**2).sum(1).mean()))
L=len(pseq); d0=1.24*(L-15)**(1/3)-1.8
tm=float(np.sum(1/(1+(np.linalg.norm(tp(P)-tg(Q),axis=1)/d0)**2))/L)
atoms=[]
for ri,r in enumerate(pch):
    for a in r:
        x,y,z=tp(a.pos.tolist()).round(2).tolist()
        atoms.append([round(x,2),round(y,2),round(z,2),ri,a.element.name,a.name])
# PDB strings for 3Dmol
for r in pch:
    for a in r: a.pos=gemmi.Position(*tp(a.pos.tolist()).tolist())
for r in gch:
    for a in r: a.pos=gemmi.Position(*tg(a.pos.tolist()).tolist())
pst.setup_entities(); gtst=gemmi.Structure(); gtst.add_model(gemmi.Model('1')); gtst[0].add_chain(gch); gtst.setup_entities()
out={'id':'7RLK chain D','name':'Transthyretin (wallaby)','seq':pseq,'nres':L,'natoms':len(atoms),
     'ca_rmsd':round(rmsd,2),'tm':round(tm,3),'atoms':atoms,
     'pred_pdb':pst.make_pdb_string(gemmi.PdbWriteOptions(minimal=True)),
     'gt_pdb':gtst.make_pdb_string(gemmi.PdbWriteOptions(minimal=True))}
open('../assets/data/ttr.js','w').write('// Generated by data/export_ttr.py - SimpleFold-3B prediction (Apple release) + PDB 7RLK chain D\nwindow.TTR='+json.dumps(out,separators=(',',':'))+';\n')
print(L,len(atoms),'rmsd',round(rmsd,2),'tm(fixed corr.)',round(tm,3),'matched',len(P)); print(pseq); print(gseq)
